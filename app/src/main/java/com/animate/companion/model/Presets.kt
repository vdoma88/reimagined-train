/** Small-town mystery personalities; stable IDs also support saved characters. */
data class Archetype(
    val id: String,
    val label: String,
    val emoji: String,
    val short: String,
    val prompt: String,
    /** Pitch multiplier for the synthesized voice. */
    val voicePitch: Float = 1f,
)

data class Profession(
    val id: String,
    val female: String,
    val male: String,
    val emoji: String,
    val prompt: String,
) {
    fun label(g: Gender) = if (g == Gender.MALE) male else female
}

data class Direction(
    val id: String,
    val label: String,
    val emoji: String,
    val short: String,
    val prompt: String,
)


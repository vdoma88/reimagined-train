    fun generate(gender: Gender, random: Random = Random.Default): String {
        val given = when (gender) {
            Gender.FEMALE -> female
            Gender.MALE -> male
            Gender.NEUTRAL -> unisex
        }.random(random)
        return "$given ${surnames.random(random)}"
    }

    /** Honorific the character uses for their own name in third person, cute-anime style. */
    fun suffix(gender: Gender): String = when (gender) {
        Gender.FEMALE -> "-тян"
        Gender.MALE -> "-кун"
        Gender.NEUTRAL -> "-сан"
    }
